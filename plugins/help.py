from .base import Plugin
from telethon import events
import logging
import asyncio

logger = logging.getLogger(__name__)

HELP = """  
📚 **منوی راهنمای جامع دستورات** 📚  

▬▬▬▬▬▬▬▬▬▬▬▬  
📌 **قابلیت‌های اصلی**:  
• نمایش تمام دستورات ربات در **دسته‌بندی‌های سازمان‌یافته**  
• راهنمای کامل مدیریت کاربران، پیام‌ها و تنظیمات  
• مثال‌های عملیاتی برای هر دستور  
• هشدارهای امنیتی و نکات مهم اجرایی  

▬▬▬▬▬▬▬▬▬▬▬▬  
🎯 **دستورات کلیدی**:  
• `/help` یا `راهنما` ➔ نمایش این منوی راهنما  

▬▬▬▬▬▬▬▬▬▬▬▬  
✨ **بخش‌های اصلی راهنما**:  
- مدیریت کاربران (`بن، آنبن، سکوت`)  
- مدیریت پیام‌ها (`حذف، علامت‌گذاری`)  
- ابزارهای کمکی (`OCR، تغییر سایز، دانلود`)  
- تنظیمات پیشرفته (`پنل، شبیه‌سازی فعالیت‌ها`)  
- اطلاعات مالی (`نرخ ارز، تبدیل واحد`)  

⚠️ **نکات مهم**:  
- راهنما به صورت خودکار پس از ۲ دقیقه حذف می‌شود  
- فقط برای **مالک ربات** قابل مشاهده است  
- دستورات حساس نیاز به دسترسی ادمین دارند  
"""

class HelpPlugin(Plugin):
    def __init__(self, client, config, user_id):
        super().__init__(client, config)
        self.owner_id = str(user_id)
        logger.info(f"HelpPlugin initialized for owner: {self.owner_id}")

    async def initialize(self, me):
        self.me = me

    async def handle_events(self):
        @self.client.on(events.NewMessage(pattern=r'^(?:/help|راهنما)$'))
        async def help_handler(event):
            if str(event.sender_id) != self.owner_id:
                return
            try:
                help_text = """\
📚 **راهنمای کامل دستورات ربات**

---

### 🛠 **مدیریت کاربران**
این دستورات برای مدیریت کاربران در گروه‌ها و کانال‌ها استفاده می‌شوند.

- `/ban [یوزرنیم/آی‌دی]`: بن کردن کاربر.
  - **مثال**: `/ban @username` یا `/ban 123456789`
  - **نکته**: فقط ادمین‌ها می‌توانند از این دستور استفاده کنند.

- `/unban [یوزرنیم/آی‌دی]`: آنبن کردن کاربر.
  - **مثال**: `/unban @username` یا `/unban 123456789`

- `/banall`: بن کردن تمام کاربران گروه.
  - **هشدار**: این دستور بسیار قدرتمند است و باید با احتیاط استفاده شود.

- `/mute [یوزرنیم/آی‌دی]`: ساکت کردن کاربر.
  - **مثال**: `/mute @username` یا `/mute 123456789`

- `/unmute [یوزرنیم/آی‌دی]`: لغو سکوت کاربر.
  - **مثال**: `/unmute @username` یا `/unmute 123456789`

- `/mutelist`: نمایش لیست کاربران ساکت‌شده.

- `/cleanmute`: پاک‌کردن تمام سکوت‌ها.

---

### 📩 **مدیریت پیام‌ها**
این دستورات برای مدیریت پیام‌ها در گروه‌ها، کانال‌ها و پیام‌های خصوصی استفاده می‌شوند.

- `/del [تعداد]`: حذف تعداد مشخصی از پیام‌ها.
  - **مثال**: `/del 10` (حذف ۱۰ پیام آخر)

- `/markreadgroup`: علامت‌گذاری پیام‌های گروه به عنوان خوانده شده.

- `/markreadpv`: علامت‌گذاری پیام‌های خصوصی به عنوان خوانده شده.

- `/markreadchannel`: علامت‌گذاری پیام‌های کانال به عنوان خوانده شده.

---

### 🔧 **ابزارهای کمکی**
این دستورات برای انجام کارهای مختلف مفید هستند.

- `/id`: نمایش اطلاعات کامل کاربر یا گروه/کانال.
  - **مثال**: پاسخ به یک پیام با `/id` برای دریافت اطلاعات فرستنده.

- `/ocr`: استخراج متن از تصویر.
  - **مثال**: پاسخ به یک تصویر با `/ocr`.

- `/ocr numbers`: استخراج اعداد از تصویر.
  - **مثال**: پاسخ به یک تصویر با `/ocr numbers`.

- `/ocr email`: استخراج ایمیل‌ها از تصویر.
  - **مثال**: پاسخ به یک تصویر با `/ocr email`.

- `/ocr links`: استخراج لینک‌ها از تصویر.
  - **مثال**: پاسخ به یک تصویر با `/ocr links`.

- `/resize [عرض] [ارتفاع]`: تغییر اندازه تصویر.
  - **مثال**: `/resize 800 600`.

- `/dl [لینک]`: دانلود رسانه از لینک.
  - **مثال**: `/dl https://example.com/image.jpg`.

- `/time`: نمایش زمان فعلی.

---

### 🎨 **تنظیمات فرمت متن**
این دستورات برای تغییر فرمت متن استفاده می‌شوند.

- `/bold`: متن را پررنگ می‌کند.
- `/italic`: متن را ایتالیک می‌کند.
- `/underline`: متن را زیرخط‌دار می‌کند.
- `/strike`: متن را خط‌خورده می‌کند.
- `/code`: متن را به صورت کد نمایش می‌دهد.
- `/pre`: متن را به صورت بلوک کد نمایش می‌دهد.
- `/clearformat`: پاک‌کردن تمام فرمت‌ها.

---

### ⚙️ **تنظیمات پیشرفته**
این دستورات برای تنظیمات پیشرفته ربات استفاده می‌شوند.

- `/panel`: نمایش پنل کنترل ربات.
- `/typing`: شبیه‌سازی تایپ کردن.
- `/upload`: شبیه‌سازی آپلود فایل.
- `/record`: شبیه‌سازی ضبط ویدیو یا صدا.
- `/interactive`: شبیه‌سازی فعالیت‌های تعاملی.
- `/call`: شبیه‌سازی تماس صوتی یا ویدیویی.
- `/allactions`: کنترل تمام فعالیت‌های شبیه‌سازی‌شده.

---

### 💰 **دستورات مالی**
این دستورات برای نمایش اطلاعات مالی و تبدیل ارز استفاده می‌شوند.

- `/finance`: نمایش اطلاعات بازارهای مالی (ارز، طلا، رمزارز).
- `[مقدار] [ارز] به [ارز]`: تبدیل مقدار مشخصی از یک ارز به ارز دیگر.
  - **مثال**: `100 دلار به تومن` یا `50 تومن به دلار`.

---

### ⚠️ **نکات مهم**
- **دسترسی ادمین**: بسیاری از دستورات نیاز به دسترسی ادمین دارند.
- **محدودیت‌های حجمی**: در دانلود فایل‌ها محدودیت‌هایی وجود دارد.
- **فرمت‌ها**: فرمت‌های متن بلافاصله ویرایش می‌شوند.
- **احتیاط**: دستوراتی مانند `/banall` باید با احتیاط استفاده شوند.

---
  
💡 **راهنمای استفاده از ربات**:
1. **شروع کار**: ابتدا ربات را به گروه یا کانال خود اضافه کنید و دسترسی ادمین بدهید.
2. **دستورات پایه**: از دستورات پایه مانند `/id` و `/time` برای آشنایی با ربات استفاده کنید.
3. **مدیریت کاربران**: از دستورات مدیریتی مانند `/ban` و `/mute` برای کنترل کاربران استفاده کنید.
4. **ابزارهای کمکی**: از دستورات مانند `/ocr` و `/resize` برای انجام کارهای خاص استفاده کنید.
5. **تنظیمات پیشرفته**: برای تنظیمات پیشرفته از دستوراتی مانند `/panel` و `/typing` استفاده کنید.

---  

🚀 **راهنمای پشتیبانی**:
- در صورت بروز مشکل، از دستور `/ping` برای بررسی وضعیت ربات استفاده کنید.
- برای گزارش مشکلات، با پشتیبانی تماس بگیرید.

---

"""
                msg = await event.reply(help_text)
                await asyncio.sleep(120)
                await msg.delete()
                await event.delete()
            except Exception as e:
                logger.error(f"Help command error: {str(e)}")
